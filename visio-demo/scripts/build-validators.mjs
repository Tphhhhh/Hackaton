// Compile schemas at build time: the browser never needs eval or new Function.
import fs from 'node:fs';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
const root = new URL('../', import.meta.url);
fs.mkdirSync(new URL('src/generated/', root), { recursive: true });
for (const [name, path] of [['result','reference/schema.json'],['tracking','integration/tracking.schema.json'],['metadata','integration/metadata.schema.json']]) {
 const ajv=new Ajv2020({allErrors:true,strict:false,code:{source:true,esm:true,lines:true}});
 let code=standaloneCode(ajv,ajv.compile(JSON.parse(fs.readFileSync(new URL(path,root)))));
 // Ajv's standalone ESM contains CommonJS runtime helper references. Bridge them
 // explicitly so both Node tests and Vite/browser use the same static validator.
 const imports=[];let n=0;
 code=code.replace(/require\("(ajv\/dist\/runtime\/[^"\n]+)"\)\.default/g,(_match,path)=>{
  const id=`runtime${n++}`;imports.push(`import ${id} from '${path}.js';`);
  return `(${id}.default || ${id})`;
 });
 if(/require\(/.test(code))throw new Error('Unrecognized Ajv runtime helper');
 fs.writeFileSync(new URL(`src/generated/${name}.js`,root),'// Generated by npm run validators; do not edit.\n'+imports.join('\n')+'\n'+code);
}
